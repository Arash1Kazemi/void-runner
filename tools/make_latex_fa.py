"""
make_latex_fa.py -- the project documentation in Persian (right to left), as LaTeX:
docs/latex_fa/VOID_RUNNER_documentation_fa.tex (+ figures/), compiled with XeLaTeX + xepersian.

Same sections, pictures and tables as tools/make_doc.py and tools/make_latex.py: it runs
the same section functions, and every English text is replaced by its Persian translation
from tools/fa_text.json (English text -> Persian text). The code itself stays in English
(left to right). A text without a translation stays English and is listed at the end, so
after changing the English documentation, add the new texts to fa_text.json.

Usage (from the project folder, after `python tests/host/run_tests.py` built build/sim.exe):
    python tools/make_latex_fa.py            write the .tex and compile it
    python tools/make_latex_fa.py --no-pdf   only write the .tex
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import make_doc as md                                        # noqa: E402
import make_latex as ml                                      # noqa: E402

OUT_DIR = ROOT / 'docs' / 'latex_fa'
TEX = OUT_DIR / 'VOID_RUNNER_documentation_fa.tex'
FA = json.loads((ROOT / 'tools' / 'fa_text.json').read_text(encoding='utf-8'))
missing = []
real_esc, ml_rich = ml.esc, ml.rich  # make_latex's own (swapped while writing)

PERSIAN = re.compile(r'[\u0600-\u06FF]')
# A run of Latin words inside a Persian sentence (kept left to right): "Arduino Mega 2560",
# "W A S D", "Timer3", "!d" ... Parentheses stay outside, so they mirror with the Persian text.
LATIN_RUN = re.compile(r"[A-Za-z!][A-Za-z0-9_.\-/!:+=#'&]*(?: [A-Za-z0-9!][A-Za-z0-9_.\-/!:+=#'&]*)*")


def translate(text):
    text = str(text)
    if not text or not re.search(r'[A-Za-z]', text) or PERSIAN.search(text):
        return text
    if text in FA:
        return FA[text]
    code_like = (re.fullmatch(r'\w+\(.*\)', text)                       # function signatures
                 or (re.fullmatch(r'[\w ./:!-]+', text)                  # names, LED words
                     and not re.search(r'[a-z]{3,} [a-z]{3,}', text)))   # (two English words = prose)
    if not code_like and text not in missing:
        missing.append(text)
    return text


def plain(text):
    """Escapes a (translated) text; Latin runs inside Persian are wrapped in \\lr{}."""
    if not PERSIAN.search(text):
        return '\\lr{%s}' % real_esc(text) if re.search(r'[A-Za-z]', text) else real_esc(text)
    out, pos = [], 0
    for m in LATIN_RUN.finditer(text):
        out.append(real_esc(text[pos:m.start()]))
        run = real_esc(m.group())
        if len(m.group()) <= 30:             # short Latin phrase: never split over two lines
            run = run.replace(' ', '~')
        out.append('\\lr{%s}' % run)
        pos = m.end()
    out.append(real_esc(text[pos:]))
    return ''.join(out)


def fa_rich(text):
    """Translates a text and formats its **bold** and `code` parts."""
    text = translate(text)
    out = []
    for part in re.split(r'(\*\*.+?\*\*|`.+?`)', text):
        if part.startswith('**'):
            out.append('\\textbf{%s}' % plain(part[2:-2]))
        elif part.startswith('`'):
            out.append('\\lr{\\texttt{%s}}' % real_esc(part[1:-1]))
        else:
            out.append(plain(part))
    return ''.join(out)


def fa_esc(text):
    return plain(translate(text))


class FaTexDoc(ml.TexDoc):
    def code(self, text, lang):
        self.w('\\begin{latin}\n')
        super().code(text, lang)
        self.w('\\end{latin}\n\n')


PREAMBLE = (ml.PREAMBLE
            .replace('\\usepackage{fontspec}\n\\IfFontExistsTF{Arial}{\\setmainfont{Arial}}{}\n'
                     '\\IfFontExistsTF{Consolas}{\\setmonofont{Consolas}}{}\n', '')
            .replace('\\usepackage[hidelinks,bookmarksnumbered=false]{hyperref}\n',
                     '\\usepackage[hidelinks,bookmarksnumbered=false]{hyperref}\n'
                     '\\usepackage{xepersian}\n'
                     '\\settextfont{Tahoma}\n'
                     '\\setlatintextfont{Arial}\n'
                     '\\IfFontExistsTF{Consolas}{\\setlatinmonofont{Consolas}}{}\n')
            .replace('GENERATED by tools/make_latex.py', 'GENERATED by tools/make_latex_fa.py'))

COVER_FA = {
    'university': '[نام دانشگاه]',
    'faculty': '[دانشکده / گروه]',
    'course': 'سیستم‌های دیجیتال ۲ (ریزپردازنده)',
    'project': 'پروژهٔ ۱',
    'student': '[نام دانشجو]',
    'student_id': '[شمارهٔ دانشجویی]',
    'teacher': '[نام استاد]',
    'semester': '[نیم‌سال، مثلاً پاییز ۱۴۰۵]',
    'date': '[تاریخ تحویل]',
}


def cover(doc):
    c = COVER_FA
    rows = [('دانشجو', c['student']), ('شمارهٔ دانشجویی', c['student_id']),
            ('استاد', c['teacher']), ('درس', c['course']), ('نیم‌سال', c['semester']),
            ('تاریخ', c['date']), ('بستر', 'Arduino Mega 2560، شبیه‌سازی‌شده در Wokwi'),
            ('کد منبع', md.COVER['repo'])]
    table = '\n'.join('\\textbf{\\color{accent}%s} & %s \\\\' % (plain(k), plain(v)) for k, v in rows)
    doc.w(r"""\begin{titlepage}\centering
\vspace*{2cm}
{\Large\bfseries %s\par}\vspace{4pt}
{\large %s\par}\vspace{1cm}
{\large %s\par}\vspace{2pt}
{\color{grey}%s\par}\vspace{2.2cm}
{\fontsize{40}{46}\selectfont\bfseries\color{accent}\lr{VOID RUNNER}\par}\vspace{8pt}
{\Large %s\par}\vspace{6pt}
{\color{grey}%s\par}
\vspace{2.5cm}
{\large\begin{tabular}{@{}l@{\hspace{1.5cm}}l@{}}
%s
\end{tabular}\par}
\vfill
\end{titlepage}
""" % (plain(c['university']), plain(c['faculty']), plain(c['course']), plain(c['project']),
       plain('یک بازی تیراندازی فضایی عمودی روی Arduino Mega'),
       plain('۴۳۲ LED تکی · صفحه‌کلید ۹ دکمه‌ای · ۴ بازر · بدون ماژول و کتابخانه'), table))


def main():
    ml.FIG_DIR = OUT_DIR / 'figures'                  # the writer copies pictures here
    pics = md.make_media()
    if ml.FIG_DIR.exists():
        shutil.rmtree(ml.FIG_DIR)
    ml.FIG_DIR.mkdir(parents=True)
    doc = FaTexDoc()
    doc.w(PREAMBLE)
    cover(doc)
    # The writer formats every text with ml.esc / ml.rich: for this document they translate.
    ml.esc, ml.rich = fa_esc, fa_rich
    md.hardware_page(doc, pics)
    md.performance(doc, pics)
    md.code_part(doc, pics)
    ml.esc, ml.rich = real_esc, ml_rich
    doc.w('\\end{document}\n')
    TEX.write_text(''.join(doc.out), encoding='utf-8', newline='\n')
    print('wrote', TEX, '(%d figures)' % len(doc.figs))
    if missing:
        print('%d texts have no Persian translation (left in English):' % len(missing))
        for t in missing:
            print('  ', t[:100])
    if '--no-pdf' in sys.argv:
        return
    for _ in range(2):
        r = subprocess.run(['xelatex', '-interaction=nonstopmode', '-halt-on-error', TEX.name],
                           cwd=OUT_DIR, capture_output=True, text=True, errors='replace')
        if r.returncode:
            print(r.stdout[-3000:])
            sys.exit('xelatex failed')
    for ext in ('.aux', '.log', '.out', '.toc'):
        (OUT_DIR / (TEX.stem + ext)).unlink(missing_ok=True)
    print('wrote', TEX.with_suffix('.pdf'))


if __name__ == '__main__':
    main()
